export function monthLabel(language: Language, month: string): string {
  // Some browsers ship Intl without Uzbek month names and return "M10".
  if (language === "uz")
    return `${uzbekMonths[Number(month.slice(5, 7)) - 1]}, ${month.slice(0, 4)}`;
  return new Intl.DateTimeFormat("ru-RU", {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${month}-01T12:00:00Z`));
}
export function chartDayLabel(
  language: Language,
  month: string,
  day: string,
): string {
  if (language === "uz")
    return `${day}-${uzbekMonths[Number(month.slice(5, 7)) - 1].toLowerCase()}`;
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    timeZone: "UTC",
  }).format(new Date(`${month}-${day.padStart(2, "0")}T12:00:00Z`));
}

export function entryDescription(
  language: Language,
  entry: { description: string; demoDescription?: string },
): string {
  return entry.demoDescription === entry.description
    ? translate(language, entry.description)
    : entry.description;
}
