export type Language = "uz" | "ru";
export const localeFor = (language: Language) =>
  language === "ru" ? "ru-RU" : "uz-UZ";
export const normalizeLanguage = (value: string | null): Language =>
  value === "ru" ? "ru" : "uz";
export function translate(
  language: Language,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const phrase =
    language === "ru"
      ? Object.hasOwn(russian, key)
        ? russian[key]
        : key
      : key;
  return phrase.replace(/\{(\w+)\}/g, (match, name: string) =>
    String(values[name] ?? match),
  );
}
export function formatMoney(
  language: Language,
  amount: string | number,
): string {
  return new Intl.NumberFormat(localeFor(language), {
    maximumFractionDigits: 2,
  }).format(Number(amount));
}
const uzbekMonths = [
  "Yanvar",
  "Fevral",
  "Mart",
  "Aprel",
  "May",
  "Iyun",
  "Iyul",
  "Avgust",
  "Sentabr",
  "Oktabr",
  "Noyabr",
  "Dekabr",
];
export function monthLabel(language: Language, month: string): string {
  // Some browsers ship Intl without Uzbek month names and return "M10".
  if (language === "uz")
    return `${uzbekMonths[Number(month.slice(5, 7)) - 1]}, ${month.slice(0, 4)}`;
  return new Intl.DateTimeFormat("ru-RU", {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${month}-01T12:00:00Z`));
}
export function chartDayLabel(
  language: Language,
  month: string,
  day: string,
): string {
  if (language === "uz")
    return `${day}-${uzbekMonths[Number(month.slice(5, 7)) - 1].toLowerCase()}`;
  return new Intl.DateTimeFormat("ru-RU", {
    day: "numeric",
    month: "long",
    timeZone: "UTC",
  }).format(new Date(`${month}-${day.padStart(2, "0")}T12:00:00Z`));
}

export function entryDescription(
  language: Language,
  entry: { description: string; demoDescription?: string },
): string {
  return entry.demoDescription === entry.description
    ? translate(language, entry.description)
    : entry.description;
}
